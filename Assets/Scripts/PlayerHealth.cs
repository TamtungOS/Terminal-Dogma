using TMPro;
using Unity.VisualScripting;
using UnityEngine;
using UnityEngine.SceneManagement;

public class PlayerHealth : MonoBehaviour
{
    [SerializeField] private TMP_Text ringText;
    [SerializeField] private float invincibleTime = 1f;

    [Header("Drop Rings")]
    [SerializeField] private SimplePool droppedRingsPool;
    [SerializeField] private int maxDroppedRings = 15;
    [SerializeField] private float scatterSpeed = 8f;

    private int rings = 0;
    private float invincibleTimer = 0f;

    private void Update()
    {
        if (invincibleTimer > 0f)
        {
            invincibleTimer = invincibleTime - Time.deltaTime;
        }
    }

    public int GetRings()
    {
        return rings;
    }

    public void AddRing()
    {
        rings++;
        ringText.text = "Rings: " + rings;
    }

    public void TakeHit()
    {
        if (invincibleTimer <= 0f)
        {
            invincibleTimer = invincibleTime;

            if (rings > 0)
            {
                ScatterRings();
                rings = 0;
                ringText.text = "Rings: 0";
            }
            else
            {
                string currentScene = SceneManager.GetActiveScene().name;
                SceneManager.LoadScene(currentScene);
            }
        }
    }
    // Scatter Rings Logic was Generated by Claude Opus 5.5
private void ScatterRings()
{
    // Drop as many rings as the player had, up to the maximum
    int ringsToDrop = rings;
    if (ringsToDrop > maxDroppedRings)
    {
        ringsToDrop = maxDroppedRings;
    }

    for (int i = 0; i < ringsToDrop; i++)
    {
        GameObject obj = droppedRingsPool.GetFromPool();

        if (obj != null)
        {
            // Start the ring at the player's position
            obj.transform.position = transform.position;

            // Pick a random direction that goes upward and to either side
            float sideways = Random.Range(-1f, 1f);
            float upward = Random.Range(0.5f, 1f);
            Vector2 direction = new Vector2(sideways, upward);

            DropRings droppedRing = obj.GetComponent<DropRings>();
            droppedRing.Launch(droppedRingsPool, this, direction * scatterSpeed);
        }
    }
}
}
